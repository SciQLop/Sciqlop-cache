"""Type checkers see the real API.

The package ships ``py.typed`` and a stub of the compiled extension, generated by
nanobind's stubgen and committed. Without the stub, every method a wrapper inherits
from the extension (count, evict_tag, size, ...) is ``Any`` to mypy and pyright.
"""

import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest

import pysciqlop_cache

PKG = os.path.dirname(pysciqlop_cache.__file__)
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
STUB = os.path.join(REPO, "pysciqlop_cache", "_pysciqlop_cache.pyi")


def _stubgen():
    found = sorted(glob.glob(os.path.join(REPO, "subprojects", "nanobind-*", "src", "stubgen.py")))
    return found[-1] if found else None


def _without_build_options(stub):
    # BLOSC2_AVAILABLE's value follows -Dwith_blosc2, its type doesn't.
    return re.sub(r"^(BLOSC2_AVAILABLE: bool) = .*$", r"\1", stub, flags=re.M)


def _has_mypy():
    try:
        import mypy  # noqa: F401
        return True
    except ImportError:
        return False


USAGE = '''
from pysciqlop_cache import Cache, FanoutCache, Index

cache = Cache("c")
n: int = cache.count()
removed: int = cache.evict_tag("t")
size: int = Index("i").size()
shards: int = FanoutCache("f").shard_count()
bad: str = cache.count()
'''


class Typing(unittest.TestCase):
    def test_package_ships_its_types(self):
        self.assertTrue(os.path.exists(os.path.join(PKG, "py.typed")))
        self.assertTrue(os.path.exists(os.path.join(PKG, "_pysciqlop_cache.pyi")))

    # simplify: compared on Linux only, the platform the stub is generated on.
    # Upgrade if a binding ever gets platform-specific types.
    @unittest.skipUnless(_stubgen() and sys.platform == "linux" and os.path.exists(STUB),
                         "needs nanobind's sources and a source checkout, on Linux")
    def test_committed_stub_matches_the_bindings(self):
        with tempfile.TemporaryDirectory() as d:
            out = os.path.join(d, "_pysciqlop_cache.pyi")
            subprocess.run([sys.executable, _stubgen(), "-q", "-m",
                            "pysciqlop_cache._pysciqlop_cache", "-o", out],
                           check=True, cwd=d,
                           env={**os.environ, "PYTHONPATH": os.path.dirname(PKG)})
            with open(out) as fresh, open(STUB) as committed:
                self.assertEqual(
                    _without_build_options(fresh.read()), _without_build_options(committed.read()),
                    "the bindings changed: regenerate pysciqlop_cache/_pysciqlop_cache.pyi "
                    "(see the comment in pysciqlop_cache/meson.build)")

    @unittest.skipUnless(_has_mypy(), "mypy not installed")
    def test_mypy_sees_the_extension_types(self):
        d = tempfile.mkdtemp()
        try:
            src = os.path.join(d, "usage.py")
            with open(src, "w") as f:
                f.write(USAGE)
            result = subprocess.run(
                [sys.executable, "-m", "mypy", "--no-incremental", "--follow-imports=silent",
                 "--cache-dir", os.path.join(d, ".mypy"), src],
                capture_output=True, text=True, cwd=d,
                env={**os.environ, "MYPYPATH": os.path.dirname(PKG)})
            errors = [l for l in result.stdout.splitlines() if ": error:" in l]
            self.assertEqual(len(errors), 1, result.stdout)
            self.assertIn("usage.py:9", errors[0])
        finally:
            shutil.rmtree(d, ignore_errors=True)


if __name__ == "__main__":
    unittest.main()
